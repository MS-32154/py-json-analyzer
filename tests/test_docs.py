"""Keep README.md and docs/index.md in sync with the code.

Each test is parametrized per code block (or per reference), so a failure
names the file and line to fix.
"""

import ast
import importlib
import inspect
import json
import re
from pathlib import Path

import pytest
from json_explorer.codegen import create_generator
from json_explorer.main import create_parser

ROOT = Path(__file__).parent.parent
DOCS = {
    name: (ROOT / name).read_text(encoding="utf-8")
    for name in ("README.md", "docs/index.md")
}


def blocks(language: str) -> list:
    """(id, code) for every fenced block of a language, as pytest params."""
    params = []
    for name, text in DOCS.items():
        for m in re.finditer(rf"```{language}\n(.*?)```", text, re.DOTALL):
            line = text[: m.start()].count("\n") + 1
            params.append(pytest.param(m.group(1), id=f"{name}:{line}"))
    return params


PYTHON_BLOCKS = blocks("python")
JSON_BLOCKS = blocks("json")
SHELL_BLOCKS = blocks("bash")


@pytest.mark.parametrize("code", PYTHON_BLOCKS)
def test_python_example_parses(code: str) -> None:
    ast.parse(code)


@pytest.mark.parametrize("code", PYTHON_BLOCKS)
def test_documented_imports_exist(code: str) -> None:
    for node in ast.walk(ast.parse(code)):
        if isinstance(node, ast.ImportFrom) and (node.module or "").startswith(
            "json_explorer"
        ):
            module = importlib.import_module(node.module)
            missing = [a.name for a in node.names if not hasattr(module, a.name)]
            assert not missing, f"{node.module} has no {', '.join(missing)}"


@pytest.mark.parametrize("code", PYTHON_BLOCKS)
def test_generated_code_samples_are_valid(code: str) -> None:
    """Samples of generated Python must run (they are real generator output)."""
    if not code.startswith("# Code generated by json_explorer"):
        pytest.skip("not a generated-code sample")
    exec(compile(code, "<doc sample>", "exec"), {"__name__": "doc_sample"})


@pytest.mark.parametrize("code", JSON_BLOCKS)
def test_json_config_examples_load(code: str) -> None:
    config = json.loads(code)
    keys = {"package_name", "language_config", "add_comments"}
    if not (isinstance(config, dict) and keys & set(config)):
        pytest.skip("not a generator configuration")
    options = config.get("language_config", {})
    python = any(
        k == "style" or k.startswith(("dataclass", "pydantic")) for k in options
    )
    create_generator("python" if python else "go", config)


# A line that runs the CLI (not e.g. "pytest --cov=json_explorer")
COMMAND = re.compile(r"^\s*(?:\$\s*)?(?:uv run\s+)?(?:python -m\s+)?json_explorer\b")


@pytest.mark.parametrize("code", SHELL_BLOCKS)
def test_documented_cli_flags_exist(code: str) -> None:
    # Lines that run json_explorer, or option lists ("--flag  # comment")
    lines = [
        line.split("#", 1)[0]
        for line in code.splitlines()
        if COMMAND.match(line) or line.lstrip().startswith("--")
    ]
    if not lines:
        pytest.skip("no json_explorer command")
    known = {o for action in create_parser()._actions for o in action.option_strings}
    flags = set(re.findall(r"(?<![\w-])(--[a-zA-Z][\w-]*)", "\n".join(lines)))
    unknown = flags - known
    assert not unknown, f"unknown flags: {', '.join(sorted(unknown))}"


def _anchor(heading: str) -> str:
    return re.sub(r"[^\w\- ]", "", heading.lower()).strip().replace(" ", "-")


@pytest.mark.parametrize("name", list(DOCS))
def test_table_of_contents_links(name: str) -> None:
    text = DOCS[name]
    anchors = {_anchor(h) for h in re.findall(r"^#+ (.+)$", text, re.MULTILINE)}
    broken = [a for a in re.findall(r"\]\(#([\w\-]+)\)", text) if a not in anchors]
    assert not broken, f"broken links: {broken}"


def _documented_signatures() -> list:
    params = []
    text = DOCS["docs/index.md"]
    for m in re.finditer(r"^#{4,5} `(\w+)\((.*?)\)`", text, re.MULTILINE):
        line = text[: m.start()].count("\n") + 1
        params.append(pytest.param(m.group(1), m.group(2), id=f"{m.group(1)}:{line}"))
    return params


def _find_callable(name: str):
    from json_explorer import DataStatsAnalyzer, JsonSearcher, JSONVisualizer
    from json_explorer.codegen.interactive import CodegenInteractiveHandler
    from json_explorer.tree_view import JsonTreeBuilder

    for cls in (
        JsonSearcher,
        DataStatsAnalyzer,
        JSONVisualizer,
        JsonTreeBuilder,
        CodegenInteractiveHandler,
    ):
        if inspect.isfunction(getattr(cls, name, None)):
            return getattr(cls, name)
    for module in (
        "json_explorer",
        "json_explorer.codegen",
        "json_explorer.codegen.core",
        "json_explorer.tree_view",
        "json_explorer.utils",
        "json_explorer.ui",
        "json_explorer.stats",
        "json_explorer.visualizer",
        "json_explorer.analyzer",
    ):
        obj = getattr(importlib.import_module(module), name, None)
        if callable(obj) and not inspect.isclass(obj):
            return obj
    return None


@pytest.mark.parametrize(("name", "args"), _documented_signatures())
def test_documented_signatures_match(name: str, args: str) -> None:
    func = _find_callable(name)
    assert func is not None, f"{name}() is documented but doesn't exist"
    params = [
        p for p in inspect.signature(func).parameters.values() if p.name != "self"
    ]
    named = {p.name for p in params if p.kind not in (p.VAR_KEYWORD, p.VAR_POSITIONAL)}
    has_var_kw = any(p.kind is p.VAR_KEYWORD for p in params)
    parts = [a.strip() for a in args.split(",") if a.strip()]
    documented = {a.split("=")[0].strip() for a in parts if not a.startswith("*")}
    # **options in the docs may stand for **kwargs in the code
    documents_var_kw = any(a.startswith("**") for a in parts)
    assert not documented - named, f"not in the code: {sorted(documented - named)}"
    assert named <= documented, f"missing from the docs: {sorted(named - documented)}"
    assert documents_var_kw == has_var_kw, "**keyword arguments documented wrongly"
