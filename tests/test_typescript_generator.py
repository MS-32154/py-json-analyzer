"""Tests for the TypeScript generator (no Node needed; see test_codegen_compiles)."""

import pytest
from json_explorer.codegen import ConfigError, create_generator, quick_generate
from json_explorer.codegen.languages.typescript.naming import (
    js_string,
    property_key,
    ts_type_name,
)

DATA = [
    {"id": 1, "name": "A", "email": None, "first-name": "x", "v": 1, "tags": ["a"]},
    {"id": 2, "name": "B", "email": "b@x", "v": "s", "tags": [], "nick": "b"},
]


def interfaces(data=DATA) -> str:
    return quick_generate(data, "typescript")


def zod(data=DATA) -> str:
    return quick_generate(data, "typescript", style="zod")


class TestNaming:
    @pytest.mark.parametrize(
        ("name", "ident"),
        [("user_address", "UserAddress"), ("123", "Type123"), ("Record", "Record_")],
    )
    def test_type_names(self, name, ident):
        assert ts_type_name(name) == ident

    @pytest.mark.parametrize(
        ("key", "rendered"),
        [
            ("userId", "userId"),
            ("$ref", "$ref"),
            ("first-name", '"first-name"'),
            ("123", '"123"'),
            ('q"k', "'q\"k'"),
        ],
    )
    def test_property_keys(self, key, rendered):
        assert property_key(key) == rendered

    def test_unicode_identifiers_unquoted(self):
        """Prettier leaves identifiers unquoted, including Unicode ones."""
        assert property_key("名前") == "名前"

    def test_proto_key_is_computed_in_object_literals(self):
        """`__proto__:` in an object literal sets the prototype, not a key."""
        assert property_key("__proto__") == "__proto__"
        assert property_key("__proto__", object_literal=True) == '["__proto__"]'
        assert '  ["__proto__"]: z.string(),' in zod({"__proto__": "x"})

    def test_js_string_escapes(self):
        assert js_string("line\nbreak") == '"line\\nbreak"'


class TestInterfaces:
    def test_header_and_export(self):
        code = interfaces()
        assert code.startswith("// Code generated by json_explorer. DO NOT EDIT.\n")
        assert "export interface Root {" in code

    def test_optional_vs_nullable(self):
        code = interfaces()
        assert "  email: string | null;" in code  # present, sometimes null
        assert "  nick?: string;" in code  # sometimes missing

    def test_keys_kept_and_quoted(self):
        assert '  "first-name"?: string;' in interfaces()

    def test_mixed_values_are_unions(self):
        assert "  v: number | string;" in interfaces()

    def test_arrays(self):
        code = interfaces({"m": [[1, None]], "u": []})
        assert "  m: (number | null)[][];" in code
        assert "  u: unknown[];" in code

    def test_nested_types_named_after_keys(self):
        code = interfaces({"team": {"lead": {"id": 1}}})
        assert "export interface Lead {" in code
        assert "  lead: Lead;" in code

    def test_formats_documented_as_strings(self):
        code = interfaces({"at": "2024-01-01T10:00:00Z"})
        assert "  /** RFC 3339 date-time */\n  at: string;" in code

    def test_no_comments(self):
        code = quick_generate({"at": "2024-01-01T10:00:00Z"}, "ts", add_comments=False)
        assert "/**" not in code


class TestZod:
    def test_schema_and_inferred_type(self):
        code = zod()
        assert 'import { z } from "zod";' in code
        assert "export const Root = z.object({" in code
        assert "export type Root = z.infer<typeof Root>;" in code

    def test_optional_vs_nullable(self):
        code = zod()
        assert "  email: z.string().nullable()," in code
        assert "  nick: z.string().optional()," in code

    def test_integers_and_unions(self):
        code = zod()
        assert "  id: z.number().int()," in code
        assert "  v: z.union([z.number().int(), z.string()])," in code

    @pytest.mark.parametrize(
        ("value", "validator"),
        [
            ("2024-01-01T10:00:00Z", "z.iso.datetime({ offset: true })"),
            ("2024-01-01T10:00:00", "z.iso.datetime({ local: true })"),
            ("2024-01-01", "z.iso.date()"),
            ("P1D", "z.iso.duration()"),
            ("10:30:00", "z.string()"),  # z.iso.time() rejects offsets
        ],
    )
    def test_format_validators(self, value, validator):
        assert f"  v: {validator}," in zod({"v": value})


class TestConfig:
    def test_alias_and_style_flag_value(self):
        assert create_generator("ts", {"style": "zod"}).ts_config.style == "zod"

    def test_invalid_style(self):
        with pytest.raises(ConfigError, match="interface, zod"):
            create_generator("typescript", {"style": "classes"})
