"""Tests for the Rust generator (no toolchain needed; see test_codegen_compiles)."""

import pytest
from json_explorer.codegen import ConfigError, create_generator, quick_generate
from json_explorer.codegen.languages.rust.naming import (
    rust_field_name,
    rust_string,
    rust_type_name,
)

DATA = [
    {"userId": 1, "email": None, "type": "t", "v": 1, "tags": ["a"], "nick": "a"},
    {"userId": 2, "email": "b@x", "type": "u", "v": "s", "tags": []},
]


def rust(data=DATA, **options) -> str:
    return quick_generate(data, "rust", **options)


class TestNaming:
    @pytest.mark.parametrize(
        ("key", "ident"),
        [
            ("userId", "user_id"),
            ("type", "r#type"),  # keyword: raw identifier
            ("self", "self_"),  # can't be a raw identifier
            ("123abc", "field_123abc"),
            ("名前", "field"),  # ASCII only; rename keeps the key
        ],
    )
    def test_field_names(self, key, ident):
        assert rust_field_name(key) == ident

    @pytest.mark.parametrize(
        ("name", "ident"),
        [("user_address", "UserAddress"), ("string", "StringType"), ("9", "Type9")],
    )
    def test_type_names(self, name, ident):
        assert rust_type_name(name) == ident

    def test_string_literals(self):
        assert rust_string('q"k') == '"q\\"k"'
        assert rust_string("a\x01b") == '"a\\u{1}b"'
        assert rust_string("名前") == '"名前"'


class TestStructs:
    def test_header_and_derives(self):
        code = rust()
        assert code.startswith("// Code generated by json_explorer. DO NOT EDIT.\n")
        assert "use serde::{Deserialize, Serialize};" in code
        assert "#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]" in code

    def test_rename_and_raw_identifiers(self):
        code = rust()
        assert '    #[serde(rename = "userId")]\n    pub user_id: i64,' in code
        assert "    pub r#type: String," in code  # serde uses "type"

    def test_null_vs_missing(self):
        code = rust()
        assert "    pub email: Option<String>," in code  # present, sometimes null
        assert (
            '    #[serde(skip_serializing_if = "Option::is_none")]\n'
            "    pub nick: Option<String>," in code
        )

    def test_mixed_values_use_serde_json_value(self):
        code = rust()
        assert "use serde_json::Value;" in code
        assert "    pub v: Value," in code

    def test_value_import_only_when_used(self):
        assert "serde_json" not in rust({"a": 1})

    def test_arrays(self):
        code = rust({"m": [[1, None]], "o": [{"a": 1}, None]})
        assert "    pub m: Vec<Vec<Option<i64>>>," in code
        assert "    pub o: Vec<Option<OItem>>," in code

    def test_deny_unknown_fields(self):
        assert "#[serde(deny_unknown_fields)]" in rust(deny_unknown_fields=True)
        assert "deny_unknown_fields" not in rust()

    def test_formats_documented(self):
        assert "    /// RFC 3339 date-time\n    pub at: String," in rust(
            {"at": "2024-01-01T10:00:00Z"}
        )


def test_invalid_option():
    with pytest.raises(ConfigError, match="Unknown rust option"):
        create_generator("rs", {"style": "x"})
