GO_DECODE_MAIN = """package main

import (


	"encoding/json"
	"os"
)

func main() {
	data, err := os.ReadFile("data.json")
	if err != nil {
		panic(err)
	}
	var v %s
	if err := json.Unmarshal(data, &v); err != nil {
		os.Stderr.WriteString(err.Error())
		os.Exit(1)
	}
}
"""

# Root is generated for objects and arrays of objects
DECODE_CASES = [
    case
    for case, data in CASES.items()
    if isinstance(data, dict) or (data and all(isinstance(x, dict) for x in data))
]


@pytest.mark.parametrize("case", DECODE_CASES)
def test_go_decodes_source_data(case: str, tmp_path: Path) -> None:
    go = _find_go()
    if go is None:
        pytest.skip("Go toolchain not found (set JSON_EXPLORER_GO or add go to PATH)")
    data = CASES[case]
    write(tmp_path / "go.mod", "module example.com/decode\n\ngo 1.22\n")
    write(tmp_path / "models.go", quick_generate(data, "go"))
    root = "[]Root" if isinstance(data, list) else "Root"
    write(tmp_path / "main.go", GO_DECODE_MAIN % root)
    write(tmp_path / "data.json", json.dumps(data))
    result = subprocess.run(
        [go, "run", "."],
        cwd=tmp_path,
        capture_output=True,
        encoding="utf-8",
        check=False,
    )
    assert result.returncode == 0, result.stderr


@pytest.mark.parametrize("case", DECODE_CASES)
def test_pydantic_validates_source_data(case: str) -> None:
    import pydantic

    data = CASES[case]
    namespace: dict[str, typing.Any] = {"__name__": "generated"}
    exec(quick_generate(data, "python", style="pydantic"), namespace)
    root = namespace["Root"]
    adapter = pydantic.TypeAdapter(list[root] if isinstance(data, list) else root)
    adapter.validate_python(data)


def test_typeddict_null_vs_missing() -> None:
    """#23: a TypedDict must accept the data it was generated from."""
    data = [{"name": "A", "email": None, "nick": "a"}, {"name": "B", "email": "b@x"}]
    code = quick_generate(data, "python", style="typeddict")
    assert "email: str | None" in code  # present, possibly null
    assert "nick: NotRequired[str]" in code  # may be missing, never null
    assert "name: str" in code


# ---------------------------------------------------------------------------
# TypeScript: tsc --strict, prettier, and decoding with the generated types.
# Needs node and a directory with typescript, zod and prettier installed
# (JSON_EXPLORER_TS_TOOLS=<dir containing node_modules>); skipped otherwise.
# ---------------------------------------------------------------------------

TSCONFIG = {
    "compilerOptions": {
        "strict": True,
        "target": "es2022",
        "module": "nodenext",
        "moduleResolution": "nodenext",
        "skipLibCheck": True,
        "outDir": "out",
    }
}


def _ts_workdir(workdir: Path, models: str) -> Path:
    """A throwaway ES module project around models.ts; returns the tools dir."""
    tools = os.environ.get("JSON_EXPLORER_TS_TOOLS")
    if not tools or shutil.which("node") is None:
        pytest.skip("TypeScript tools not found (set JSON_EXPLORER_TS_TOOLS)")
    modules = Path(tools) / "node_modules"
    if not all((modules / pkg).is_dir() for pkg in ("typescript", "zod", "prettier")):
        pytest.skip("JSON_EXPLORER_TS_TOOLS lacks typescript, zod or prettier")
    (workdir / "node_modules").symlink_to(modules, target_is_directory=True)
    write(workdir / "package.json", '{"type": "module"}\n')
    write(workdir / "tsconfig.json", json.dumps(TSCONFIG))
    write(workdir / "models.ts", models)
    return modules


def _run(cmd: list[str], workdir: Path) -> None:
    result = subprocess.run(
        cmd, cwd=workdir, capture_output=True, encoding="utf-8", check=False
    )
    assert result.returncode == 0, result.stdout + result.stderr


def check_typescript(code: str, workdir: Path) -> None:
    """tsc --strict accepts the code and prettier leaves it unchanged."""
    assert code.startswith("// Code generated by json_explorer. DO NOT EDIT.\n")
    modules = _ts_workdir(workdir, code)
    _run(["node", str(modules / "typescript/bin/tsc"), "--noEmit", "-p", "."], workdir)
    _run(
        ["node", str(modules / "prettier/bin/prettier.cjs"), "--check", "models.ts"],
        workdir,
    )


@pytest.mark.parametrize("case", DECODE_CASES)
def test_typescript_interfaces_accept_source_data(case: str, tmp_path: Path) -> None:
    """The data, written as a TypeScript literal of the root type, type-checks."""
    data = CASES[case]
    modules = _ts_workdir(tmp_path, quick_generate(data, "typescript"))
    root = "Root[]" if isinstance(data, list) else "Root"
    write(
        tmp_path / "data.ts",
        f'import type {{ Root }} from "./models.js";\n'
        f"export const data: {root} = {json.dumps(data)};\n",
    )
    _run(["node", str(modules / "typescript/bin/tsc"), "--noEmit", "-p", "."], tmp_path)


@pytest.mark.parametrize("case", DECODE_CASES)
def test_zod_schemas_parse_source_data(case: str, tmp_path: Path) -> None:
    data = CASES[case]
    modules = _ts_workdir(tmp_path, quick_generate(data, "typescript", style="zod"))
    write(tmp_path / "data.ts", f"export const data: unknown = {json.dumps(data)};\n")
    write(
        tmp_path / "decode.ts",
        'import { z } from "zod";\n'
        'import { data } from "./data.js";\n'
        'import { Root } from "./models.js";\n'
        "(Array.isArray(data) ? z.array(Root) : Root).parse(data);\n",
    )
    _run(["node", str(modules / "typescript/bin/tsc"), "-p", "."], tmp_path)
    _run(["node", "out/decode.js"], tmp_path)


# ---------------------------------------------------------------------------
# Rust: cargo check (warnings are errors), rustfmt, and decoding with serde.
# Needs cargo (JSON_EXPLORER_CARGO or PATH); skipped otherwise. All crates
# share one target directory, so serde is compiled once.
# ---------------------------------------------------------------------------

CARGO_TOML = """[package]
name = "generated"
version = "0.1.0"
edition = "2024"

[dependencies]
serde = { version = "1", features = ["derive"] }
serde_json = "1"
"""
RUST_TARGET = Path(tempfile.gettempdir()) / "json_explorer_rust_target"


def _cargo() -> str:
    cargo = os.environ.get("JSON_EXPLORER_CARGO") or shutil.which("cargo")
    if cargo is None:
        pytest.skip(
            "Rust toolchain not found (set JSON_EXPLORER_CARGO or add cargo to PATH)"
        )
    return cargo


def _rust_crate(workdir: Path, models: str, main: str = "fn main() {}\n") -> str:
    cargo = _cargo()
    (workdir / "src").mkdir()
    write(workdir / "Cargo.toml", CARGO_TOML)
    write(workdir / "src/lib.rs", models)
    write(workdir / "src/main.rs", main)
    return cargo


def _run_cargo(cargo: str, args: list[str], workdir: Path) -> None:
    env = os.environ | {
        "RUSTFLAGS": "-D warnings",
        "CARGO_TARGET_DIR": str(RUST_TARGET),
    }
    result = subprocess.run(
        [cargo, *args],
        cwd=workdir,
        env=env,
        capture_output=True,
        encoding="utf-8",
        check=False,
    )
    assert result.returncode == 0, result.stderr


def check_rust(code: str, workdir: Path) -> None:
    """cargo check accepts the code without warnings; rustfmt leaves it unchanged."""
    assert code.startswith("// Code generated by json_explorer. DO NOT EDIT.\n")
    cargo = _rust_crate(workdir, code)
    _run_cargo(cargo, ["check", "--quiet"], workdir)
    rustfmt = Path(cargo).with_name("rustfmt")
    _run(
        [
            str(rustfmt) if rustfmt.exists() else "rustfmt",
            "--check",
            "--edition",
            "2024",
            "src/lib.rs",
        ],
        workdir,
    )


@pytest.mark.parametrize("case", DECODE_CASES)
@pytest.mark.parametrize("deny_unknown", [False, True], ids=["default", "deny-unknown"])
def test_rust_decodes_source_data(
    case: str, deny_unknown: bool, tmp_path: Path
) -> None:
    data = CASES[case]
    models = quick_generate(data, "rust", deny_unknown_fields=deny_unknown)
    root = "Vec<generated::Root>" if isinstance(data, list) else "generated::Root"
    write(tmp_path / "data.json", json.dumps(data))
    main = (
        "fn main() {\n"
        f"    let _decoded: {root} =\n"
        '        serde_json::from_str(include_str!("../data.json")).expect("decode");\n'
        "}\n"
    )
    cargo = _rust_crate(tmp_path, models, main)
    _run_cargo(cargo, ["run", "--quiet"], tmp_path)
