TARGETS = (
    "dataclass",
    "pydantic",
    "typeddict",
    "go",
    "ts-interface",
    "ts-zod",
    "rust",
)


def _params():
    for case in CASES:
        for target in TARGETS:
            yield pytest.param(case, target, id=f"{case}-{target}")


def _find_go() -> str | None:
    return os.environ.get("JSON_EXPLORER_GO") or shutil.which("go")


def check_python(code: str) -> None:
    """Execute generated Python, resolve every class's annotations, and
    require ruff-format-clean output."""
    assert code.startswith("# Code generated by json_explorer. DO NOT EDIT.\n")
    formatted = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--check",
            "--stdin-filename",
            "g.py",
            "-",
        ],
        input=code,
        capture_output=True,
        encoding="utf-8",
        check=False,
    )
    assert formatted.returncode == 0, "generated Python is not ruff-format clean"
    namespace: dict[str, typing.Any] = {"__name__": "generated"}
    exec(compile(code, "<generated>", "exec"), namespace)
    classes = [
        obj
        for obj in namespace.values()
        if isinstance(obj, type) and obj.__module__ == "generated"
    ]
    assert classes, "no classes were generated"
    for cls in classes:
        if hasattr(cls, "model_rebuild"):  # Pydantic: resolve forward refs now
            cls.model_rebuild()
        typing.get_type_hints(cls)


def check_go(code: str, workdir: Path) -> None:
    """Type-check generated Go with `go vet` in a throwaway module."""
    go = _find_go()
    if go is None:
        pytest.skip("Go toolchain not found (set JSON_EXPLORER_GO or add go to PATH)")
    write(workdir / "go.mod", "module example.com/generated\n\ngo 1.22\n")
    write(workdir / "models.go", code)
    result = subprocess.run(
        [go, "vet", "./..."],
        cwd=workdir,
        capture_output=True,
        encoding="utf-8",
        check=False,
    )
    assert result.returncode == 0, result.stderr

    gofmt = shutil.which("gofmt", path=str(Path(go).parent)) or shutil.which("gofmt")
    unformatted = subprocess.run(
        [gofmt, "-l", "models.go"],
        cwd=workdir,
        capture_output=True,
        encoding="utf-8",
        check=True,
    )
    assert unformatted.stdout == "", "generated Go is not gofmt-clean"
    assert code.startswith("// Code generated by json_explorer. DO NOT EDIT.\n")


@pytest.mark.parametrize(("case", "target"), list(_params()))
def test_generated_code_compiles(case: str, target: str, tmp_path: Path) -> None:
    data = CASES[case]
    if target == "go":
        check_go(quick_generate(data, "go", package_name="models"), tmp_path)
    elif target == "rust":
        check_rust(quick_generate(data, "rust"), tmp_path)
    elif target.startswith("ts-"):
        style = target.removeprefix("ts-")
        check_typescript(quick_generate(data, "typescript", style=style), tmp_path)
    else:
        check_python(quick_generate(data, "python", style=target))


def test_typeddict_keeps_json_keys() -> None:
    """A TypedDict describes the dict as-is, so its keys must be the JSON keys."""
    data = {"userID": 1, "first-name": "Ada", "type": "admin"}
    namespace: dict[str, typing.Any] = {"__name__": "generated"}
    exec(quick_generate(data, "python", style="typeddict"), namespace)
    root = namespace["Root"]
    assert set(typing.get_type_hints(root)) == set(data)


